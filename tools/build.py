"""Bundle local CommonJS modules without downloading build dependencies."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
modules = {}


def collect(path):
    key = path.relative_to(ROOT).as_posix()
    if key in modules:
        return key
    source = path.read_text(encoding="utf-8")
    modules[key] = ""

    def resolve(match):
        dependency = (path.parent / match[1]).with_suffix(".js").resolve()
        return "require(" + json.dumps(collect(dependency)) + ")"

    source = re.sub(r"require\(['\"](\.[^'\"]+)['\"]\)", resolve, source)
    modules[key] = source
    return key


entry = collect(ROOT / "src/plugin.js")
output = ["// Generated by python tools/build.py. Edit src/, then rebuild.\n",
          "// MCPSkins Manager by Mjonter. Blockbench desktop 5.2.2+.\n",
          "(function (nativeRequire) {\n'use strict';\nconst modules = {\n"]
for key, source in modules.items():
    output.append(json.dumps(key) + ": function(module, exports, require) {\n" + source + "\n},\n")
output += ["};\nconst cache = Object.create(null);\n",
           "function require(id) {\n if (!modules[id]) return nativeRequire(id);\n",
           " if (!cache[id]) { const m = cache[id] = {exports: {}}; modules[id](m, m.exports, require); }\n",
           " return cache[id].exports;\n}\n",
           "require(" + json.dumps(entry) + ")(nativeRequire);\n",
           "})(typeof requireNativeModule === 'function' ? requireNativeModule : require);\n"]
destination = ROOT / "mcpskins_asset_manager.js"
destination.write_text("".join(output), encoding="utf-8", newline="\n")
print(f"Built {destination.name}: {len(modules)} modules, {destination.stat().st_size:,} bytes")
